import { chromium } from 'playwright';
import { mkdir, rename } from 'node:fs/promises';

await mkdir('artifacts/video', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: false });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, recordVideo: { dir: 'artifacts/video', size: { width: 1440, height: 1000 } } });
const page = await context.newPage();
await page.goto('http://127.0.0.1:4321/', { waitUntil: 'networkidle' });
await page.evaluate(async () => { await document.fonts.ready; });
await page.waitForTimeout(1600);
await page.locator('#work').scrollIntoViewIfNeeded();
await page.waitForTimeout(1800);
await page.getByRole('button', { name: 'Developer tools', exact: true }).click();
await page.waitForTimeout(1300);
await page.getByRole('button', { name: 'All projects' }).click();
await page.waitForTimeout(800);
await page.locator('.project-info h3 a').filter({ hasText: 'StreamTrack' }).click();
await page.waitForTimeout(1500);
await page.locator('.case-body').scrollIntoViewIfNeeded();
await page.waitForTimeout(1800);
await page.locator('.gallery-section').scrollIntoViewIfNeeded();
await page.waitForTimeout(1200);
await page.locator('.gallery-trigger').first().click();
await page.waitForTimeout(1600);
await page.keyboard.press('Escape');
await page.goto('http://127.0.0.1:4321/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Switch to dark theme' }).click();
await page.waitForTimeout(1800);
await page.locator('#about').scrollIntoViewIfNeeded();
await page.waitForTimeout(1800);
await page.locator('#contact').scrollIntoViewIfNeeded();
await page.waitForTimeout(2000);
const video = page.video();
await context.close();
if (video) await rename(await video.path(), 'artifacts/video/portfolio-walkthrough.webm');
await browser.close();
console.log('artifacts/video/portfolio-walkthrough.webm');
